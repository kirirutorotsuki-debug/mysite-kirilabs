<?php
// if (...) — проверяем условие.
// session_status() — функция, которая узнает текущее состояние сессий на сервере.
// PHP_SESSION_NONE — константа, которая означает «сессия еще не была запущена».
// === — оператор строгого сравнения (значения и типы должны полностью совпадать).
if (session_status() === PHP_SESSION_NONE) {
    
    // session_start() — включает механизм сессий. 
    // Сервер связывается с браузером и позволяет использовать массив $_SESSION для запоминания данных.
    session_start();
}

// Создаем массив $allowed_langs. Это наш «белый список» поддерживаемых языков.
// Сюда мы внесли короткие коды: русский (ru), английский (en) и финский (fi).
// Если в будущем добавится новый язык, его нужно будет просто дописать в этот список через запятую.
$allowed_langs = ['ru', 'en', 'fi'];

// Создаем переменную $lang и записываем в неё стандартное значение 'ru'.
// Это базовый язык сайта. Если пользователь зайдет впервые и ничего не выберет, применится он.
$lang = 'ru';

// isset() — функция, которая проверяет: «Существует ли переменная и не пустая ли она?».
// $_GET['lang'] — глобальный массив PHP, куда попадают параметры из адресной строки после знака ? (например: ?lang=fi).
// Вся строчка означает: «Если пользователь прямо сейчас кликнул по ссылке переключения языка»:
if (isset($_GET['lang'])) {
    
    // in_array() — функция, которая ищет значение в массиве. 
    // Она проверяет: «То, что пользователь передал в ?lang=..., вообще есть в нашем белом списке $allowed_langs?».
    // ? : — это тернарный оператор (короткий if/else). Работает так: (УСЛОВИЕ) ? ВАРИАНТ_ДА : ВАРИАНТ_НЕТ;
    // Если переданный язык разрешен (например, 'fi'), он запишется в переменную $lang. 
    // Если там передан бред или хакерская попытка взлома, сработает защита и запишется безопасный 'ru'.
    $lang = in_array($_GET['lang'], $allowed_langs) ? $_GET['lang'] : 'ru';
    
    // Записываем очищенный и проверенный язык в сессию на сервере.
    // Теперь сервер будет помнить выбор пользователя, пока тот ходит по разным страницам сайта.
    $_SESSION['lang'] = $lang;
    
    // setcookie() — команда браузеру пользователя сохранить файл-куки на его компьютере.
    // 'lang' — имя этого куки-файла.
    // $lang — значение, которое сохраняем (текущий язык).
    // time() + (3600 * 24 * 30) — время жизни куки. Текущее время в секундах + секунды на 30 дней вперед.
    // "/" — куки будут работать во всех папках и на всех страницах вашего домена.
    setcookie('lang', $lang, time() + (3600 * 24 * 30), "/");
} 
// elseif — «иначе, если клика по ссылке не было, проверяем следующее условие»:
// isset($_SESSION['lang']) — проверяем, сохранен ли уже язык в сессии сервера с прошлых кликов.
// && — оператор «И» (оба условия слева и справа должны быть верными).
// in_array(...) — на всякий случай проверяем, что язык из сессии все еще находится в нашем белом списке.
elseif (isset($_SESSION['lang']) && in_array($_SESSION['lang'], $allowed_langs)) {
    
    // Если в сессии лежит правильный язык, достаем его и перезаписываем им нашу переменную $lang.
    $lang = $_SESSION['lang'];
} 
// elseif — «иначе, если в сессии тоже пусто (например, пользователь закрыл браузер и вернулся на сайт завтра)»:
// Проверяем, остался ли у пользователя на компьютере долговечный куки-файл с языком и безопасен ли он.
elseif (isset($_COOKIE['lang']) && in_array($_COOKIE['lang'], $allowed_langs)) {
    
    // Если куки найдены, берем сохраненное значение оттуда и записываем в переменную $lang.
    $lang = $_COOKIE['lang'];
}

// require — команда жесткого подключения внешнего файла. Если файла не окажется, сайт выдаст ошибку и остановится.
// "lang/{$lang}.php" — PHP автоматически подставит значение переменной внутрь строки.
// Если в $lang сейчас лежит 'fi', путь превратится в "lang/fi.php".
// Команда return внутри языкового файла вернет массив слов, и мы запишем его целиком в переменную $txt.
$txt = require "lang/{$lang}.php";
?>
